uint8_t OLED_FrameBuffer[1024];
uint8_t *OLED_Frame_ptr = OLED_FrameBuffer;
uint8_t *OLED_BufferPage_ptr = OLED_FrameBuffer;


void OLED_Init(void)
{
    I2C1_Init();

    OLED_SendCommand_V1(OLED_DISPLAY_OFF);

    OLED_SendCommand_V2(OLED_SET_DISPLAY_CLOCK_DIV, 0x80);

    OLED_SendCommand_V2(OLED_SET_MULTIPLEX_RATIO, 0x3F);

    OLED_SendCommand_V2(OLED_SET_DISPLAY_OFFSET, 0x00);

    OLED_SendCommand_V1(OLED_SET_START_LINE);

    OLED_SendCommand_V2(OLED_SET_CHARGE_PUMP, 0x14);

    OLED_SendCommand_V2(OLED_SET_MEMORY_MODE, OLED_HORIZONTAL_ADDRESSING);

    OLED_SendCommand_V1(OLED_SEGMENT_REMAP);

    OLED_SendCommand_V1(OLED_COM_SCAN_DEC);

    OLED_SendCommand_V2(OLED_SET_COM_PINS_CONFIG, 0x12);

    OLED_SendCommand_V2(OLED_SET_CONTRAST, 0xCF);

    OLED_SendCommand_V2(OLED_SET_PRECHARGE_PERIOD, 0xF1);

    OLED_SendCommand_V2(OLED_SET_VCOMH_LEVEL, 0x40);

    OLED_SendCommand_V1(OLED_DISPLAY_RESUME_RAM);

    OLED_SendCommand_V1(OLED_DISPLAY_NORMAL);

    OLED_SendCommand_V1(OLED_DISPLAY_ON);

}

void OLED_SendCommand_V1(uint8_t command)
{
    I2C1_Start();

    I2C1_SendAddress(OLED_I2C_ADDRESS,0);

    I2C1_SendByte(OLED_CONTROL_COMMAND);

    I2C1_SendByte(command);

    I2C1_Stop();
}

void OLED_SendCommand_V2(uint8_t command, uint8_t value)
{
    I2C1_Start();

    I2C1_SendAddress(OLED_I2C_ADDRESS,0);

    I2C1_SendByte(OLED_CONTROL_COMMAND);

    I2C1_SendByte(command);

    I2C1_SendByte(value);

    I2C1_Stop();
}
void OLED_SendCommand_V3(uint8_t command, uint8_t value1,uint8_t value2)
{
    I2C1_Start();

    I2C1_SendAddress(OLED_I2C_ADDRESS,0);

    I2C1_SendByte(OLED_CONTROL_COMMAND);

    I2C1_SendByte(command);

    I2C1_SendByte(value1);

    I2C1_SendByte(value2);

    I2C1_Stop();
}

void OLED_SendData(const uint8_t *buffer)
{
    I2C1_Start();

    I2C1_SendAddress(OLED_I2C_ADDRESS, I2C_WRITE);

    I2C1_SendByte(OLED_CONTROL_DATA);

    for(uint16_t i = 0; i < 1024; i++)
    {
        I2C1_SendByte(*buffer);
		buffer++;
    }

    I2C1_Stop();
}

void OLED_SetCursor(uint8_t page, uint8_t column)
{
    OLED_SendCommand_V3(OLED_SET_PAGE_ADDRESS,page,page);

    OLED_SendCommand_V3(OLED_SET_COLUMN_ADDRESS,column,127);
}

void OLED_ClearFrameBuffer(void)
{
    for(uint16_t i =0; i<1024; i++)
    {
        OLED_FrameBuffer[i]=0x00;
    }
}

void OLED_UpdateScreen(void)
{
    OLED_SetCursor(0,0);
    OLED_SendData(OLED_FrameBuffer);
}

const uint8_t *Font5x7_add(char c)
{
    if (c < 32 || c > 126)
    {
        c = '?';
    }

    return &Font5x7[(c - 32) * 5];
}

void OLED_Write(char *ptr)
{

	while(*ptr)
	{
		const uint8_t *x =Font5x7_add(*ptr);
		for(uint8_t i=0; i<5; i++)
		{
			*OLED_BufferPage_ptr = *x;
			OLED_BufferPage_ptr++;
			x++;
		}
		*OLED_BufferPage_ptr = 0x00;
		OLED_BufferPage_ptr++;
		ptr++;
	}

}


void Move_Buffer_ptr(uint8_t page ,uint8_t column)
{
	if(column>=127)
	{
		column=127;
	}
	else if(page>=7)
	{
		page=7;
	}
	OLED_BufferPage_ptr = OLED_Frame_ptr+(page*128);
	OLED_BufferPage_ptr += column;                   // we will move bit by bit not by the character spacing
}

